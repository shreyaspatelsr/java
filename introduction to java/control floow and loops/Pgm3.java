
public class Pgm3 {
    // post increment and pre increment

    public static void main(String[] args) {
        int a = 20;
        int b = a++;
        System.out.println("a = " + a);
        System.out.println("b = " + b);
        int c = 40;
        int d = ++c;
        System.out.println("c = " + c);
        System.out.println("d = " + d);
    }
}
